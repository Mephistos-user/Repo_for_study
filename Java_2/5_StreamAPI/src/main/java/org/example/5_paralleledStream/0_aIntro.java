// Потоки параллельной обработки:

/* Параллельные потоки данных позволяют выполнять операции над элементами потока
одновременно в нескольких потоках (threads). Это может существенно улучшить
производительность при обработке больших объемов данных, используя многопроцессорные
возможности современных компьютеров. */

/* Преимущества и ограничения параллельной обработки данных
Преимущества
    1. Улучшение производительности: Параллельная обработка позволяет быстрее
выполнять операции над большими наборами данных, так как операции выполняются
одновременно в нескольких потоках.
    2. Простота использования: Stream API предоставляет удобный метод
parallelStream(), который делает переключение к параллельной обработке очень
простым. */

/* Когда параллельная обработка эффективна:
    - Большие объемы данных:
Параллельная обработка наиболее эффективна, когда нужно обрабатывать большие
объемы данных. Например, если у вас есть миллион элементов, параллельная обработка
может значительно сократить время выполнения по сравнению с последовательной
обработкой.
    - Комплексные и длительные операции:
Если операции, выполняемые над элементами потока, являются вычислительно
сложными и требуют значительных временных затрат (например, сложные вычисления,
операции ввода-вывода), параллельная обработка может дать значительное ускорение.
    - Многоядерные процессоры:
Если ваше приложение работает на машине с многоядерным процессором,
параллельная обработка сможет использовать несколько ядер для выполнения задач
одновременно, что увеличивает общую производительность. */

/* Когда параллельная обработка может быть неэффективна:
    - Маленькие объемы данных:
Накладные расходы на создание и управление параллельными потоками могут
превышать выгоду от параллельной обработки, если объем данных невелик. В таких
случаях последовательная обработка будет быстрее.
    - Простые и быстрые операции:
Если операции над элементами потока просты и быстро выполняются, затраты на
синхронизацию и управление потоками могут сделать параллельную обработку менее
эффективной.
    - Ввод-вывод (I/O) операции:
При работе с I/O операциями (например, чтение и запись файлов, работа с базами
данных) параллельная обработка может не принести ожидаемой выгоды из-за
ограничений пропускной способности и необходимости синхронизации доступа к
ресурсам.
    - Проблемы потокобезопасности:
Если операции над элементами потока не являются потокобезопасными и требуют
синхронизации, накладные расходы на управление блокировками могут снизить
производительность параллельной обработки. */

/* Ограничения
    1. Распределение нагрузки: Не все задачи подходят для параллельной обработки. Для
небольших наборов данных или задач, требующих синхронизации, параллельная
обработка может даже замедлить выполнение.
Способ преодоления: Перед применением параллельных потоков рекомендуется
провести тесты и профилирование, чтобы убедиться, что параллельная обработка
действительно приносит выгоду в данном конкретном случае.
    2. Потокобезопасность: При параллельной обработке нужно быть осторожным с
изменяемыми данными. Модификация данных в нескольких потоках может привести к
несогласованности данных.
Способ преодоления: Стремитесь к использованию неизменяемых объектов.
Неизменяемые объекты не могут быть изменены после создания, что устраняет риск
несогласованности данных.
    3. Перегрузка системы: Параллельная обработка может создавать дополнительную
нагрузку на процессор и другие ресурсы системы, что может быть нежелательно в
некоторых условиях.
Способ преодоления: Используйте ForkJoinPool для управления количеством потоков,
используемых параллельными потоками. Следите за нагрузкой на систему и избегайте
запуска слишком большого числа параллельных задач, которые могут исчерпать
ресурсы. */
