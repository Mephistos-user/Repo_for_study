// Анонимные классы
/* В Java анонимный класс - это класс без имени, который определяется и создается
одновременно. Они обычно используются для реализации интерфейсов или наследования
абстрактных классов в ситуациях, когда не требуется повторное использование класса в
других местах программы. */

//Вот пример анонимного класса для реализации интерфейса Runnable:
Runnable myRunnable = new Runnable() {
    @Override
    public void run() {
    System.out.println("Это код, выполняемый внутри анонимного класса");
    }
};
/* Здесь мы создаем экземпляр класса, который реализует интерфейс Runnable, и определяем его
метод run() прямо на месте. Этот класс не имеет имени и используется только здесь для
создания объекта myRunnable. */

// Вот еще несколько примеров использования анонимных классов в Java:
/* Слушатель событий (Event Listener): Например, рассмотрим создание слушателя кнопки для
обработки события нажатия: */
button.addActionListener(new ActionListener() {
    @Override
    public void actionPerformed(ActionEvent e) {
        System.out.println("Кнопка была нажата");
    }
});
/* Здесь создается анонимный класс, который реализует интерфейс ActionListener и
переопределяет его метод actionPerformed. При нажатии кнопки будет вызван этот метод,
выводящий сообщение в консоль. */

/* Comparator для сортировки: Анонимные классы часто используются для создания
Comparatorов для сортировки объектов в коллекциях: */
List<String> names = Arrays.asList("John", "Alice", "Bob");
Collections.sort(names, new Comparator<String>() {
    @Override
    public int compare(String s1, String s2) {
        return s1.compareTo(s2);
    }
});
/* Здесь создается анонимный класс, реализующий интерфейс Comparator, чтобы определить
способ сравнения строк для сортировки. Метод compare() сравнивает две строки и
возвращает результат. */
/* Анонимные классы обычно применяются там, где требуется реализация одного метода, и нет
необходимости создавать отдельный класс. Однако, с появлением лямбда-выражений в Java 8,
их использование стало менее распространенным, поскольку лямбда-выражения
предоставляют более компактный и выразительный синтаксис для реализации анонимных
функций.
Лямбда-выражения - это удобный способ представления анонимных функций в Java. Они
позволяют писать более краткий и выразительный код, особенно при работе с интерфейсами,
имеющими один абстрактный метод (так называемыми функциональными интерфейсами). */
/* Лямбда-выражение имеет следующий синтаксис:
(parameter_list) -> { body }
Где: - parameter_list - список параметров метода (если метод не принимает параметры, то
список пуст) - body - тело метода */
/* Например, если у нас есть функциональный интерфейс Runnable с единственным методом
void run(), мы можем использовать лямбда-выражение для его реализации: */
Runnable runnable = () -> {
    System.out.println("Выполняется код внутри лямбда-выражения");
};
// Это эквивалентно следующему анонимному классу:
Runnable runnable = new Runnable() {
    @Override
    public void run() {
        System.out.println("Выполняется код внутри анонимного класса");
    }
};
/* Однако, лямбда-выражения позволяют писать это более кратко. Еще один пример: если у нас
есть список строк и мы хотим отсортировать его по длине строк, мы можем использовать
лямбда-выражение вместе с методом sort: */
List<String> strings = Arrays.asList("aaa", "bb", "c");
strings.sort((s1, s2) -> s1.length() - s2.length());
// Это сортирует список strings по длине строк в порядке возрастания.

// Пример лямбда-выражения с Comparator для сравнения строк по их длине.
import java.util.ArrayList;
import java.util.Collections;
import java.util.Comparator;
import java.util.List;

public class Main {
    public static void main(String[] args) {
        List<String> names = new ArrayList<>();
        names.add("Alice");
        names.add("John");
        names.add("Bob");
        // Лямбда-выражение для сравнения строк по их длине
        Comparator<String> lengthComparator = (s1, s2) -> s1.length() -
        s2.length();
        // Сортировка списка по длине строк
        Collections.sort(names, lengthComparator);
        // Вывод отсортированного списка
        System.out.println("Отсортированный список по длине строк:");
        for (String name : names) {
            System.out.println(name);
        }
    }
}
/* В этом примере: - Мы создаем список names, содержащий несколько строк. - Затем мы создаем
лямбда-выражение для сравнения строк по их длине. Мы используем метод length() для
получения длины строки и возвращаем разницу между длинами. - После этого мы используем
это лямбда-выражение в методе sort класса Collections для сортировки списка строк по
длине. - Наконец, мы выводим отсортированный список строк. */
